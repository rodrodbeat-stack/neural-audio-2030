insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('community-videos', 'community-videos', true, 104857600,
        array['video/mp4', 'video/webm', 'video/quicktime'])
on conflict (id) do update set
  name = excluded.name,
  public = true,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "community videos public read" on storage.objects;
create policy "community videos public read" on storage.objects
  for select using (bucket_id = 'community-videos');

drop policy if exists "community videos upload" on storage.objects;
create policy "community videos upload" on storage.objects
  for insert to anon, authenticated with check (bucket_id = 'community-videos');

create table if not exists public.video_posts (
  id bigint generated by default as identity primary key,
  artist text not null,
  title text not null,
  video_path text not null,
  video_url text not null,
  status text not null default 'pending' check (status in ('pending','published','rejected')),
  created_at timestamptz not null default now()
);
alter table public.video_posts enable row level security;
drop policy if exists "published videos are public" on public.video_posts;
create policy "published videos are public" on public.video_posts
  for select using (status = 'published');
drop policy if exists "anyone can submit videos to moderation" on public.video_posts;
create policy "anyone can submit videos to moderation" on public.video_posts
  for insert to anon, authenticated with check (status = 'pending');

select id, name, public, file_size_limit from storage.buckets where id = 'community-videos';
